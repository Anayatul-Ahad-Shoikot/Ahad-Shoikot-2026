-- ============================================================
-- Portfolio Database Schema (Supabase / PostgreSQL)
-- Run this in Supabase SQL Editor or via `supabase db push`
-- ============================================================

-- 1. Profile & About Me (single-row config table)
create table if not exists public.profile (
    id integer primary key default 1 check (id = 1),
    name text not null,
    title text not null,
    tagline text not null,
    email text not null,
    location text not null,
    bio text not null,
    birthday_date text not null,
    birthday_age integer not null default 25,
    avatar_url text,
    social_github text,
    social_facebook text,
    social_linkedin text,
    social_instagram text,
    accepting_projects boolean not null default true,
    updated_at timestamptz not null default now()
);

-- 2. Projects
create table if not exists public.projects (
    id bigint generated by default as identity primary key,
    title text not null,
    slug text unique,
    description text not null,
    long_description text,
    images text[] not null default '{}',
    tags text[] not null default '{}',
    github text default '#',
    live text default '#',
    featured boolean not null default false,
    year text not null,
    category text not null default 'Web App',
    sort_order integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- 3. Experiences
create table if not exists public.experiences (
    id bigint generated by default as identity primary key,
    role text not null,
    company text not null,
    period text not null,
    description text not null,
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

-- 4. Education
create table if not exists public.education (
    id bigint generated by default as identity primary key,
    degree text not null,
    tag text not null,
    year text not null,
    institution text not null,
    grade text not null,
    grade_note text,
    icon text default '🎓',
    accent text default '#FF6B2B',
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

-- 5. Skills
create table if not exists public.skills (
    id bigint generated by default as identity primary key,
    name text not null unique,
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

-- 6. Interests
create table if not exists public.interests (
    id bigint generated by default as identity primary key,
    icon text not null default '◈',
    label text not null,
    description text not null,
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

-- 7. Training & Courses
create table if not exists public.courses (
    id bigint generated by default as identity primary key,
    name text not null,
    platform text not null,
    year text not null,
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

-- 8. Certificates
create table if not exists public.certificates (
    id bigint generated by default as identity primary key,
    title text not null,
    issuer text not null,
    issue_date text not null,
    credential_url text,
    image_url text,
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

-- 9. Languages
create table if not exists public.languages (
    id bigint generated by default as identity primary key,
    name text not null,
    level text not null,
    proficiency integer not null default 50 check (proficiency >= 0 and proficiency <= 100),
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
);

-- 10. Contact Messages
create table if not exists public.contact_messages (
    id bigint generated by default as identity primary key,
    name text not null,
    email text not null,
    project_type text default 'Not specified',
    message text not null,
    is_read boolean not null default false,
    created_at timestamptz not null default now()
);

-- ============================================================
-- Row Level Security (RLS)
-- ============================================================
alter table public.profile enable row level security;
alter table public.projects enable row level security;
alter table public.experiences enable row level security;
alter table public.education enable row level security;
alter table public.skills enable row level security;
alter table public.interests enable row level security;
alter table public.courses enable row level security;
alter table public.certificates enable row level security;
alter table public.languages enable row level security;
alter table public.contact_messages enable row level security;

-- Public read access for portfolio content
create policy "Public read profile" on public.profile for select using (true);
create policy "Public read projects" on public.projects for select using (true);
create policy "Public read experiences" on public.experiences for select using (true);
create policy "Public read education" on public.education for select using (true);
create policy "Public read skills" on public.skills for select using (true);
create policy "Public read interests" on public.interests for select using (true);
create policy "Public read courses" on public.courses for select using (true);
create policy "Public read certificates" on public.certificates for select using (true);
create policy "Public read languages" on public.languages for select using (true);

-- Authenticated admin write access for portfolio content
create policy "Admin write profile" on public.profile for all to authenticated using (true) with check (true);
create policy "Admin write projects" on public.projects for all to authenticated using (true) with check (true);
create policy "Admin write experiences" on public.experiences for all to authenticated using (true) with check (true);
create policy "Admin write education" on public.education for all to authenticated using (true) with check (true);
create policy "Admin write skills" on public.skills for all to authenticated using (true) with check (true);
create policy "Admin write interests" on public.interests for all to authenticated using (true) with check (true);
create policy "Admin write courses" on public.courses for all to authenticated using (true) with check (true);
create policy "Admin write certificates" on public.certificates for all to authenticated using (true) with check (true);
create policy "Admin write languages" on public.languages for all to authenticated using (true) with check (true);

-- Contact messages: anyone can submit, only authenticated admin can read/update/delete
create policy "Anyone can submit contact message" on public.contact_messages for insert with check (true);
create policy "Admin manage contact messages" on public.contact_messages for select to authenticated using (true);
create policy "Admin update contact messages" on public.contact_messages for update to authenticated using (true) with check (true);
create policy "Admin delete contact messages" on public.contact_messages for delete to authenticated using (true);

-- ============================================================
-- Storage Bucket for Project Images & Certificates
-- ============================================================
insert into storage.buckets (id, name, public)
values ('portfolio-assets', 'portfolio-assets', true)
on conflict (id) do nothing;

create policy "Public read portfolio assets"
on storage.objects for select
using (bucket_id = 'portfolio-assets');

create policy "Authenticated upload portfolio assets"
on storage.objects for insert to authenticated
with check (bucket_id = 'portfolio-assets');

create policy "Authenticated update portfolio assets"
on storage.objects for update to authenticated
using (bucket_id = 'portfolio-assets');

create policy "Authenticated delete portfolio assets"
on storage.objects for delete to authenticated
using (bucket_id = 'portfolio-assets');
